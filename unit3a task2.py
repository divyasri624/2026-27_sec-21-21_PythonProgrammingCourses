# Create a list
numbers = [30, 10, 50, 20, 40]

print("Original list:", numbers)

# Insert an element
numbers.insert(2, 25)
print("After insert:", numbers)

# Append an element
numbers.append(60)
print("After append:", numbers)

# Remove an element
numbers.remove(10)
print("After remove:", numbers)

# Sort the list
numbers.sort()
print("After sort:", numbers)

# Reverse the list
numbers.reverse()
print("After reverse:", numbers)